#!/bin/bash
# Move the bulky, regenerable storage OFF the small /home quota onto a big scratch/
# project filesystem, and leave symlinks + an env file so everything keeps working.
#
# WHY: /home on this node is capped at ~101 GB. The 32B HF model cache (~65 GB) plus
# training checkpoints fill it, and once home is full every write fails with EDQUOT —
# which is what silently killed the k=2 rung (the process errored out and couldn't even
# write its own traceback to the full disk). Relocating the cache + runs to scratch means
# home stops hitting its ceiling and the sweep has room.
#
# USAGE (run on the login node, from the repo root):
#   bash scripts/relocate_storage.sh /path/to/scratch/base
#   #  or set VEA_STORE and omit the arg:  VEA_STORE=/path bash scripts/relocate_storage.sh
# With no target it PRINTS candidate big filesystems and exits (nothing is moved).
#
# Safe + idempotent: anything already relocated (now a symlink) is skipped; re-running is fine.
# Cross-filesystem mv copies to scratch then unlinks from home, so it works even when home is
# already full and FREES home as it goes. The k=1 adapter under runs/ moves with it, intact.
set -uo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
BASE="${1:-${VEA_STORE:-}}"

echo "=== home quota BEFORE ==="
quota -s 2>/dev/null | grep -A1 home || df -h "$HOME" | tail -1

if [ -z "$BASE" ]; then
  echo
  echo "No target given. Candidate large filesystems (pick one NOT mounted at /home,"
  echo "with lots of Avail, that compute nodes can also see):"
  df -h | awk 'NR==1 || ($4 ~ /T|P/) || $5+0 < 80' | grep -viE "tmpfs|overlay|/dev($|/)|/run" | head -30
  echo
  echo "Then re-run:  bash scripts/relocate_storage.sh <that mountpoint>/\$USER"
  echo "(create your own subdir under it, e.g. /projects/<proj>/\$USER/vea-store)"
  exit 2
fi

mkdir -p "$BASE" 2>/dev/null || { echo "!! cannot create $BASE"; exit 1; }
if ! ( : > "$BASE/.vea_write_test" ) 2>/dev/null; then echo "!! $BASE not writable"; exit 1; fi
rm -f "$BASE/.vea_write_test"

# refuse a target on the same filesystem as home (would not free anything)
home_dev="$(df --output=source "$HOME" 2>/dev/null | tail -1)"
base_dev="$(df --output=source "$BASE" 2>/dev/null | tail -1)"
if [ -n "$home_dev" ] && [ "$home_dev" = "$base_dev" ]; then
  echo "!! $BASE is on the SAME filesystem as \$HOME ($home_dev) — that won't free quota. Pick scratch/project storage."
  exit 1
fi
echo "=== relocating bulky storage -> $BASE  (home=$home_dev  base=$base_dev) ==="

# relocate one path: move src -> dest on scratch, replace src with a symlink.
# skip if src is already a symlink (done) or missing (nothing to move).
relocate() {
  local src="$1" dest="$2"
  if [ -L "$src" ]; then echo "  skip (already linked): $src -> $(readlink "$src")"; return; fi
  if [ ! -e "$src" ]; then echo "  skip (absent): $src"; return; fi
  mkdir -p "$(dirname "$dest")"
  if [ -e "$dest" ]; then echo "  !! dest exists, not overwriting: $dest  (rm it or move $src by hand)"; return; fi
  echo "  moving $src -> $dest  ($(du -sh "$src" 2>/dev/null | cut -f1)) ..."
  if command -v rsync >/dev/null; then
    rsync -a --remove-source-files "$src/" "$dest/" 2>/dev/null && find "$src" -type d -empty -delete 2>/dev/null
  else
    mv "$src" "$dest"
  fi
  rm -rf "$src" 2>/dev/null
  ln -s "$dest" "$src"
  echo "  linked: $src -> $dest"
}

# 1) HF model + dataset cache (the ~65 GB one)
relocate "$HOME/.cache/huggingface" "$BASE/huggingface"
# 2) training checkpoints/outputs (keeps the k=1 adapter; writes now land on scratch)
relocate "$REPO/runs"              "$BASE/runs"
# 3) other regenerable caches, if present
relocate "$HOME/.cache/pip"        "$BASE/cache/pip"
relocate "$HOME/.cache/torch"      "$BASE/cache/torch"
relocate "$HOME/.cache/vllm"       "$BASE/cache/vllm"

# Pick the HF cache to advertise. CRUCIAL: if an HF_HOME is already set (e.g. in
# ~/.bashrc) and really holds a model (a hub/ with at least one models--* snapshot),
# point at THAT resolved path — do NOT hardcode $BASE/huggingface, which may be empty
# and would make an offline run fail to find the model. Only fall back to $BASE/huggingface
# (where relocate() moved ~/.cache/huggingface) when no populated cache already exists.
HF_PICK="$BASE/huggingface"
_existing="$(readlink -f "${HF_HOME:-}" 2>/dev/null)"
if [ -n "$_existing" ] && ls "$_existing"/hub/models--* >/dev/null 2>&1; then
  HF_PICK="$_existing"
  echo "  HF_HOME: using existing populated cache -> $HF_PICK"
elif ls "$BASE"/huggingface/hub/models--* >/dev/null 2>&1; then
  echo "  HF_HOME: using relocated cache -> $HF_PICK"
else
  echo "  HF_HOME: WARNING no populated model cache found; defaulting to $HF_PICK (may be empty)"
fi

# env file the runners source so new writes also go to scratch (belt-and-suspenders
# on top of the symlinks above). Safe to source from any shell.
ENVF="$REPO/scripts/storage_env.sh"
cat > "$ENVF" <<EOF
# AUTO-GENERATED by scripts/relocate_storage.sh — points bulky caches/outputs at scratch.
export VEA_STORE="$BASE"
export HF_HOME="$HF_PICK"
export HF_HUB_CACHE="$HF_PICK/hub"
export HF_DATASETS_CACHE="$HF_PICK/datasets"
export PIP_CACHE_DIR="$BASE/cache/pip"
export TORCH_HOME="$BASE/cache/torch"
export TORCH_EXTENSIONS_DIR="$BASE/cache/torch_extensions"
export TRITON_CACHE_DIR="$BASE/cache/triton"
export WANDB_DIR="$BASE/wandb"
mkdir -p "$BASE/wandb" "$BASE/cache/torch_extensions" "$BASE/cache/triton" 2>/dev/null || true
EOF
echo "=== wrote $ENVF (HF_HOME=$HF_PICK) ==="

echo "=== home quota AFTER ==="
quota -s 2>/dev/null | grep -A1 home || df -h "$HOME" | tail -1
echo "=== done. Commit scripts/storage_env.sh is NOT needed (it's node-local). Now relaunch the sweep. ==="
